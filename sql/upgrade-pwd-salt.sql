-- =====================================================================
-- 密码安全加固：每用户随机盐 + SHA-256（2026-10-23）
-- 旧方案为 MD5(全局盐 + 明文)，相同密码哈希相同，可被彩虹表反查。
-- 新方案：SHA-256(随机盐 + 全局盐 + 明文)，每个账号盐不同。
-- 迁移方式：老账号 salt 为 NULL，首次登录成功后由代码自动升级（无需人工重置）。
-- =====================================================================
USE card_battle;

ALTER TABLE `users`
  ADD COLUMN `salt` varchar(32) DEFAULT NULL COMMENT '每用户随机盐(SHA-256 哈希用)' AFTER `password`;
